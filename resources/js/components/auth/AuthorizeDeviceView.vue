<template>
  <div class="w-full max-w-md bg-white rounded-3xl border border-slate-200/80 p-8 shadow-xl space-y-6 relative overflow-hidden">
    
    <!-- Countdown Badge (Active Request) -->
    <div v-if="!isExpired && timeLeft !== null" class="absolute top-4 right-4 inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-slate-100 text-[11px] font-bold text-slate-600">
      <svg class="w-3.5 h-3.5 text-slate-400" fill="none" stroke="currentColor" viewBox="0 0 24 24">
        <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 8v4l3 3m6-3a9 9 0 11-18 0 9 9 0 0118 0z"/>
      </svg>
      <span>{{ formattedTimeLeft }}</span>
    </div>

    <!-- State 1: Request Expired -->
    <div v-if="isExpired" class="text-center space-y-4 py-2">
      <div class="w-16 h-16 bg-rose-50 text-rose-600 rounded-full flex items-center justify-center mx-auto">
        <svg class="w-8 h-8" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 8v4l3 3m6-3a9 9 0 11-18 0 9 9 0 0118 0z" />
        </svg>
      </div>
      <div>
        <h2 class="text-lg font-extrabold text-slate-900">Verification Expired</h2>
        <p class="text-xs text-slate-500 mt-1">This verification session has expired. Please return to sign in to start a new authorization process.</p>
      </div>
      <a :href="'/'" class="inline-block w-full py-3.5 rounded-2xl bg-slate-900 hover:bg-slate-800 text-white text-xs font-bold transition">
        Return to Sign In
      </a>
    </div>

    <!-- State 2: Active Verification -->
    <template v-else>
      <!-- Header -->
      <div class="text-center space-y-2">
        <h2 class="text-xl font-extrabold text-slate-900">
          <template v-if="method === 'sms'">Confirm Mobile Number</template>
          <template v-else-if="method === 'authenticator'">Authenticator App Code</template>
          <template v-else>Workstation Verification</template>
        </h2>
        <p class="text-xs text-slate-500">
          <template v-if="method === 'sms'">
            Enter the mobile phone number registered to your employee profile.
          </template>
          <template v-else-if="method === 'authenticator'">
            Enter the 6-digit code generated by your Authenticator app.
          </template>
          <template v-else>
            We sent a 6-digit OTP code to <strong class="text-slate-800">{{ email }}</strong>.
          </template>
        </p>
      </div>

      <!-- Status Alert -->
      <div v-if="statusMessage" class="p-4 rounded-2xl bg-emerald-50 border border-emerald-200 text-xs text-emerald-800 font-medium">
        {{ statusMessage }}
      </div>

      <!-- Error Alert -->
      <div v-if="errorMessage" class="p-4 rounded-2xl bg-rose-50 border border-rose-200 text-xs text-rose-700 font-medium">
        {{ errorMessage }}
      </div>

      <!-- Method Switcher -->
      <div class="flex items-center justify-center gap-1 p-1 bg-slate-100 rounded-2xl text-xs font-bold">
        <!-- Email Tab Form -->
        <form method="POST" :action="routes.switchMethod" class="flex-1">
          <input type="hidden" name="_token" :value="csrfToken">
          <input type="hidden" name="method" value="email">
          <button 
            type="submit" 
            class="w-full py-1.5 rounded-xl transition"
            :class="method === 'email' ? 'bg-white text-slate-900 shadow-sm' : 'text-slate-500 hover:text-slate-800'"
          >
            Email
          </button>
        </form>

        <!-- SMS Tab Form -->
        <form v-if="hasSms" method="POST" :action="routes.switchMethod" class="flex-1">
          <input type="hidden" name="_token" :value="csrfToken">
          <input type="hidden" name="method" value="sms">
          <button 
            type="submit" 
            class="w-full py-1.5 rounded-xl transition"
            :class="method === 'sms' ? 'bg-white text-slate-900 shadow-sm' : 'text-slate-500 hover:text-slate-800'"
          >
            SMS
          </button>
        </form>

        <!-- Authenticator (2FA) Tab Form -->
        <form v-if="hasAuthenticator" method="POST" :action="routes.switchMethod" class="flex-1">
          <input type="hidden" name="_token" :value="csrfToken">
          <input type="hidden" name="method" value="authenticator">
          <button 
            type="submit" 
            class="w-full py-1.5 rounded-xl transition"
            :class="method === 'authenticator' ? 'bg-white text-slate-900 shadow-sm' : 'text-slate-500 hover:text-slate-800'"
          >
            2FA App
          </button>
        </form>
      </div>

      <!-- Dynamic Verification Form -->
      <form method="POST" :action="routes.verify" class="space-y-4">
        <input type="hidden" name="_token" :value="csrfToken">
        <div>
          <label for="otp" class="block text-xs font-bold text-slate-700 uppercase tracking-wider mb-2">
            <template v-if="method === 'sms'">Registered Contact Number</template>
            <template v-else-if="method === 'authenticator'">6-Digit 2FA Code</template>
            <template v-else>6-Digit OTP Code</template>
          </label>

          <input 
            v-if="method === 'sms'" 
            id="otp" 
            type="tel" 
            name="otp" 
            v-model="otpInput" 
            required 
            autofocus 
            class="w-full text-center text-lg font-mono px-4 py-3.5 rounded-2xl border border-slate-200 focus:border-brand focus:ring-4 focus:ring-brand/15 outline-none font-semibold transition" 
            placeholder="09171234567"
          >
          <input 
            v-else 
            id="otp" 
            type="text" 
            name="otp" 
            v-model="otpInput" 
            maxlength="6" 
            required 
            autofocus 
            class="w-full text-center text-2xl font-mono tracking-widest px-4 py-3.5 rounded-2xl border border-slate-200 focus:border-brand focus:ring-4 focus:ring-brand/15 outline-none font-semibold transition" 
            placeholder="000000"
          >
        </div>

        <button type="submit" class="w-full py-3.5 rounded-2xl bg-brand hover:bg-brand-hover text-white text-xs font-bold shadow-md transition">
          Authorize Workstation & Sign In
        </button>
      </form>

      <!-- Resend Link with Countdown (Email only) -->
      <div v-if="method === 'email'" class="text-center pt-2">
        <form method="POST" :action="routes.resend">
          <input type="hidden" name="_token" :value="csrfToken">
          <button 
            type="submit" 
            :disabled="cooldown > 0" 
            class="text-xs font-bold text-brand hover:underline disabled:opacity-50 disabled:no-underline disabled:cursor-not-allowed transition"
          >
            <span v-if="cooldown > 0">Resend code in {{ cooldown }}s</span>
            <span v-else>Didn't receive code? Resend Email OTP</span>
          </button>
        </form>
      </div>

      <!-- Return to Device Wait Screen -->
      <div v-if="authId && routes.wait" class="text-center">
        <a :href="routes.wait" class="text-xs font-semibold text-slate-400 hover:text-slate-600 transition">
          &larr; Return to Device Wait Screen
        </a>
      </div>
    </template>

  </div>
</template>

<script setup>
import { ref, computed, onMounted, onUnmounted } from 'vue';

const props = defineProps({
  method: { type: String, default: 'email' },
  email: { type: String, default: '' },
  expiresAt: { type: String, default: null }, // ISO-8601 string passed from Blade
  hasSms: { type: Boolean, default: false },
  hasAuthenticator: { type: Boolean, default: false },
  cooldownSeconds: { type: Number, default: 0 },
  statusMessage: { type: String, default: '' },
  errorMessage: { type: String, default: '' },
  authId: { type: [Number, String], default: null },
  csrfToken: { type: String, required: true },
  routes: {
    type: Object,
    required: true,
    default: () => ({
      switchMethod: '#',
      verify: '#',
      resend: '#',
      wait: '#',
    }),
  },
});

const otpInput = ref('');
const cooldown = ref(props.cooldownSeconds);
const timeLeft = ref(null);
const isExpired = ref(false);

let resendTimer = null;
let expirationTimer = null;

const formattedTimeLeft = computed(() => {
  if (timeLeft.value === null || timeLeft.value <= 0) return '00:00';
  const minutes = Math.floor(timeLeft.value / 60);
  const seconds = timeLeft.value % 60;
  return `${String(minutes).padStart(2, '0')}:${String(seconds).padStart(2, '0')}`;
});

const updateExpirationTimer = () => {
  if (!props.expiresAt) return;

  const expirationTime = new Date(props.expiresAt).getTime();
  const now = new Date().getTime();
  const diffInSeconds = Math.floor((expirationTime - now) / 1000);

  if (diffInSeconds <= 0) {
    timeLeft.value = 0;
    isExpired.value = true;
    if (expirationTimer) clearInterval(expirationTimer);
  } else {
    timeLeft.value = diffInSeconds;
  }
};

onMounted(() => {
  // Resend Cooldown Countdown
  if (cooldown.value > 0) {
    resendTimer = setInterval(() => {
      if (cooldown.value > 0) {
        cooldown.value--;
      } else {
        clearInterval(resendTimer);
      }
    }, 1000);
  }

  // Session Expiration Countdown
  if (props.expiresAt) {
    updateExpirationTimer();
    expirationTimer = setInterval(updateExpirationTimer, 1000);
  }
});

onUnmounted(() => {
  if (resendTimer) clearInterval(resendTimer);
  if (expirationTimer) clearInterval(expirationTimer);
});
</script>